def test_npmrc_env_override(monkeypatch, tmp_path):
    """NPM_CONFIG_USERCONFIG redirects the npmrc check to a custom file."""
    custom = tmp_path / "custom-npmrc"
    custom.write_text(f"//registry.npmjs.org/:_authToken={FAKE_TOKEN}\n")
    monkeypatch.setenv("NPM_CONFIG_USERCONFIG", str(custom))
    finding = CredentialAudit(home=str(tmp_path / "unused-home")).check_npmrc()
    assert finding is not None
    assert finding.severity == "high"
    assert finding.file_path == str(custom)
    assert FAKE_TOKEN not in str(finding.to_dict())  # value stays redacted


