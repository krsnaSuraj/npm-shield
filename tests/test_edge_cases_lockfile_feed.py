def test_corrupt_cache_file(tmp_path, monkeypatch):
    """Garbage in the cache file: local data survives, no crash, no timestamp."""
    feed = _make_feed(tmp_path, monkeypatch)
    feed.cache_file.write_text("{ definitely not json")
    pkgs = feed.get_affected_packages()
    assert "keyv" in pkgs  # local verified data still present
    assert pkgs["keyv"] == ["6.0.0"]
    assert feed.last_updated is None


def test_cache_file_valid(tmp_path, monkeypatch):
    """A valid cache merges extra packages with the local verified data."""
    feed = _make_feed(tmp_path, monkeypatch)
    feed.cache_file.write_text(
        json.dumps(
            {
                "fetched_at": 1700000000,
                "sources": ["https://example.invalid/advisory"],
                "packages": {"extra-pkg": ["1.0.0"], "keyv": ["9.9.9"]},
            }
        )
    )
    pkgs = feed.get_affected_packages()
    assert pkgs["extra-pkg"] == ["1.0.0"]
    assert pkgs["keyv"] == ["6.0.0", "9.9.9"]  # local + cached union
    assert feed.last_updated == 1700000000


def test_version_matches_edge():
    """Wildcard, empty-string version and empty version lists are handled."""
    assert ThreatFeed.version_matches(None, ["*"]) is True
    assert ThreatFeed.version_matches("", ["6.0.0"]) is False
    assert ThreatFeed.version_matches("6.0.0", []) is False


def test_looks_like_package_helper():
    """The HTML-noise filter rejects obvious non-package matches."""
    assert _looks_like_package("node") is False  # in _SKIP_NAMES
    assert _looks_like_package("lodash") is False  # popular benign package
    assert _looks_like_package("a") is False  # too short
    assert _looks_like_package("http") is False  # in _SKIP_NAMES


def test_fetch_failure_graceful(tmp_path, monkeypatch):
    """Every feed source failing -> update() returns False, never raises."""

    def raiser(url, timeout=12):
        raise OSError("network unreachable")

    # Isolate the feed cache: without this, a cache written by a previous
    # run/feed-update lives in the real user cache dir and last_updated
    # reads a stale timestamp, making the assertion flaky across machines.
    monkeypatch.setenv("NPM_SHIELD_FEED_CACHE", str(tmp_path / "feed_cache"))
    monkeypatch.setattr(ThreatFeed, "_fetch", raiser)
    feed = ThreatFeed(offline_mode=False)  # network path, but _fetch is broken
    assert feed.update() is False
    assert feed.last_updated is None
    assert not feed.cache_file.exists()


