"""Edge-case tests for lockfile parsing, the threat feed, persistence
hunting and the credential audit.

These tests focus on the *weird* inputs and failure modes: malformed
caches, binary lockfiles, missing subprocesses, platform switches and
secret redaction. Every check under test promises "never raises, degrades
gracefully" — these tests hold it to that promise.

No real data files are ever modified; the feed cache is redirected into
tmp_path per test via NPM_SHIELD_FEED_CACHE.
"""
import json
import subprocess
import sys
from pathlib import Path

import pytest

from npm_shield import lockfile
from npm_shield.audit import CredentialAudit
from npm_shield.feed import ThreatFeed, _looks_like_package
from npm_shield.persistence import PersistenceHunter

# Synthetic credential value — never a real secret.
FAKE_TOKEN = "npm_EDGE_FAKE_TOKEN_7d2b1e"

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _write(tmp_path, name, content):
    p = tmp_path / name
    p.write_text(content)
    return p


def _make_feed(tmp_path, monkeypatch):
    """A ThreatFeed pointed at a hermetic tmp cache dir."""
    monkeypatch.setenv("NPM_SHIELD_FEED_CACHE", str(tmp_path / "feed-cache"))
    return ThreatFeed(offline_mode=True)


