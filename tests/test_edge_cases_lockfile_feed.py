def test_npm_alias_in_package_lockfile(tmp_path):
    """npm alias entries (version: 'npm:keyv@6.0.0') resolve to the
    real package name for poisoning checks."""
    from npm_shield.lockfile import parse_package_lock
    lf = tmp_path / "package-lock.json"
    lf.write_text(json.dumps({
        "lockfileVersion": 3,
        "packages": {
            "node_modules/my-keyv": {"version": "npm:keyv@6.0.0"},
            "node_modules/real-pkg": {"version": "1.0.0"},
        },
    }))
    pkgs = parse_package_lock(str(lf))
    # alias should resolve to keyv@6.0.0, not my-keyv@npm:keyv@6.0.0
    assert pkgs.get("keyv") == "6.0.0", f"alias not resolved: {pkgs}"
    assert pkgs.get("my-keyv") is None


