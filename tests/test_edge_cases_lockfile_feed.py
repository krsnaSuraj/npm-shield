    monkeypatch.setattr("npm_shield.persistence.subprocess.run", fake_run)
    findings = PersistenceHunter(home=str(tmp_path)).check_processes()
    assert findings
    assert any(
        f.severity == "critical" and "gh-token-monitor" in (f.message or "")
        for f in findings
    )


