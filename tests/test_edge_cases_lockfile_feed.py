def test_platform_windows_skips_linux_paths(monkeypatch, tmp_path):
    """On win32 the linux ~/.config artifact must not be flagged."""
    home = tmp_path / "home"
    state = home / ".config" / "gh-token-monitor"
    state.mkdir(parents=True)
    (state / "state.json").write_text('{"watcher": "active"}')

    # sanity: the real (linux) platform DOES flag the artifact
    linux_hunter = PersistenceHunter(home=str(home))
    assert linux_hunter.check_home()

    # simulate Windows by swapping the instance platform attr
    win_hunter = PersistenceHunter(home=str(home))
    monkeypatch.setattr(win_hunter, "platform", "win32")
    assert win_hunter.check_home() == []


